// Converts the website's design tokens (../droply/app/globals.css, oklch) to hex for React
// Native, including dark mode and every room theme. Run when the website's palette changes:
//   node scripts/generate-palette.mjs [path/to/globals.css]
// Writes src/theme/palette.generated.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = process.argv[2] ?? join(root, "..", "droply", "app", "globals.css");
const css = readFileSync(cssPath, "utf8");

function oklchToHex(l, c, hDeg) {
  const h = (hDeg * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const l_ = l + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = l - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = l - 0.0894841775 * a - 1.291485548 * b;
  const L = l_ ** 3;
  const M = m_ ** 3;
  const S = s_ ** 3;
  const lin = [
    4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S,
    -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S,
    -0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S,
  ];
  const gamma = (x) => (x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055);
  return (
    "#" +
    lin
      .map((x) => Math.round(Math.min(1, Math.max(0, gamma(x))) * 255))
      .map((v) => v.toString(16).padStart(2, "0"))
      .join("")
  );
}

const camel = (name) => name.replace(/-([a-z])/g, (_, ch) => ch.toUpperCase());

function block(selector) {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = new RegExp(`(^|\\n)${escaped}\\s*\\{([^}]*)\\}`).exec(css);
  if (!match) return null;
  const out = {};
  for (const [, name, l, c, h] of match[2].matchAll(/--([a-z-]+):\s*oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)\)/g)) {
    out[camel(name)] = oklchToHex(Number(l), Number(c), Number(h));
  }
  return out;
}

const themes = ["party", "birthday", "wedding", "gaming", "study", "ocean", "sunset"];
const palette = {
  light: block(":root"),
  dark: block(".dark"),
  rooms: Object.fromEntries(
    themes.map((t) => [t, { light: block(`[data-room-theme="${t}"]`) ?? {}, dark: block(`.dark[data-room-theme="${t}"]`) ?? {} }]),
  ),
};
if (!palette.light || !palette.dark) throw new Error("Couldn't find :root / .dark tokens in " + cssPath);

const file = `// Generated by scripts/generate-palette.mjs from the website's app/globals.css. Do not edit.
export const PALETTE = ${JSON.stringify(palette, null, 2)} as const;
`;
writeFileSync(join(root, "src", "theme", "palette.generated.ts"), file);
console.log("src/theme/palette.generated.ts");
